mod typescript {
    use super::*;

    pub fn emit(doc: &Document) -> String {
        let mut out = String::new();
        out.push_str(
            "// Generated by `diagram generate-skeleton` (non-AI, deterministic).\n",
        );
        out.push_str("// Edit freely; signatures come from the canonical IR.\n\n");
        for diag in &doc.diagrams {
            emit_diagram(diag, &mut out);
        }
        if out.ends_with("\n\n") {
            out.pop();
        }
        out
    }

    fn emit_diagram(diag: &Diagram, out: &mut String) {
        match diag {
            Diagram::Class(c) => emit_class(c, out),
            Diagram::Flowchart(f) => emit_flowchart(f, out),
            Diagram::Sequence(s) => emit_sequence(s, out),
            Diagram::State(s) => emit_state(s, out),
            Diagram::Er(e) => emit_er(e, out),
            Diagram::Gantt(_) => {
                out.push_str("// Gantt charts do not map to a skeleton; nothing to emit.\n\n");
            }
        }
    }

    fn emit_class(cd: &ClassDiagram, out: &mut String) {
        // Bucket relations by `from` for inheritance/realization vs fields.
        let mut inheritance: std::collections::HashMap<&str, Vec<&Relation>> =
            std::collections::HashMap::new();
        let mut fields: std::collections::HashMap<&str, Vec<&Relation>> =
            std::collections::HashMap::new();
        for r in &cd.relations {
            match r.kind {
                RelationKind::Inheritance | RelationKind::Realization => {
                    inheritance.entry(r.from.as_str()).or_default().push(r);
                }
                _ => {
                    fields.entry(r.from.as_str()).or_default().push(r);
                }
            }
        }
        for c in &cd.classes {
            let inheritance = inheritance.get(c.id.as_str()).map(Vec::as_slice);
            let fields = fields.get(c.id.as_str()).map(Vec::as_slice);
            emit_class_decl(c, inheritance, fields, out);
        }
        for n in &cd.notes {
            out.push_str(&format!(
                "// note for {}: {}\n",
                type_ident(&n.target),
                n.text
            ));
        }
        if !cd.notes.is_empty() {
            out.push('\n');
        }
    }

    fn emit_class_decl(
        c: &Class,
        inheritance: Option<&[&Relation]>,
        fields: Option<&[&Relation]>,
        out: &mut String,
    ) {
        let stereo = c.stereotype.as_deref().unwrap_or("");
        let id = type_ident(&c.id);
        let extends = inheritance
            .map(|rs| rs.iter().filter(|r| r.kind == RelationKind::Inheritance).map(|r| type_ident(&r.to)).collect::<Vec<_>>().join(", "))
            .unwrap_or_default();
        let implements = inheritance
            .map(|rs| rs.iter().filter(|r| r.kind == RelationKind::Realization).map(|r| type_ident(&r.to)).collect::<Vec<_>>().join(", "))
            .unwrap_or_default();
        let mut head = format!("class {id}");
        if !extends.is_empty() {
            head.push_str(&format!(" extends {extends}"));
        }
        if !implements.is_empty() {
            head.push_str(&format!(" implements {implements}"));
        }
        if stereo == "interface" {
            out.push_str(&format!("interface {id} {{\n"));
            for m in &c.members {
                if let Some(sig) = ts_method_sig(m, true) {
                    out.push_str(&format!("    {sig};\n"));
                }
            }
            out.push_str("}\n\n");
            return;
        }
        if stereo == "enumeration" {
            out.push_str(&format!("enum {id} {{\n"));
            for m in &c.members {
                let variant = member_name(m);
                if !variant.is_empty() {
                    out.push_str(&format!("    {variant},\n"));
                }
            }
            out.push_str("}\n\n");
            return;
        }
        out.push_str(&format!("{head} {{\n"));
        for m in &c.members {
            if let Some(field) = ts_field_decl(m) {
                out.push_str(&format!("    {field};\n"));
            }
        }
        if let Some(fs) = fields {
            for r in fs {
                out.push_str(&format!(
                    "    {}: {}; // {} {} ({})\n",
                    ident(&r.to),
                    type_ident(&r.to),
                    arrow_str(r.kind),
                    cardinality(r),
                    if r.label.is_empty() { String::new() } else { format!(" : {}", r.label) }
                ));
            }
        }
        for m in &c.members {
            if let Some(sig) = ts_method_sig(m, false) {
                out.push_str(&format!("    {sig} {{\n        // TODO\n    }}\n"));
            }
        }
        out.push_str("}\n\n");
    }

    fn emit_flowchart(fc: &FcDiagram, out: &mut String) {
        let in_subgraph: std::collections::HashSet<&str> = fc
            .subgraphs
            .iter()
            .flat_map(|s| s.nodes.iter().map(|n| n.as_str()))
            .collect();
        for sg in &fc.subgraphs {
            emit_subgraph(sg, fc, out);
        }
        for n in &fc.nodes {
            if !in_subgraph.contains(n.id.as_str()) {
                emit_node_decl(n, out);
            }
        }
        for e in &fc.edges {
            out.push_str(&format!(
                "// {} {} {}{}\n",
                ident(&e.from),
                style_arrow(&e.style),
                ident(&e.to),
                if e.label.is_empty() {
                    String::new()
                } else {
                    format!(" // {}", e.label)
                }
            ));
        }
        if !fc.edges.is_empty() {
            out.push('\n');
        }
    }

    fn emit_subgraph(sg: &Subgraph, fc: &FcDiagram, out: &mut String) {
        let id = mod_ident(&sg.id);
        out.push_str(&format!("export namespace {id} {{\n"));
        for nid in &sg.nodes {
            if let Some(n) = fc.nodes.iter().find(|n| &n.id == nid) {
                emit_node_decl(n, out);
            }
        }
        out.push_str("}\n\n");
    }

    fn emit_node_decl(n: &Node, out: &mut String) {
        let id = ident(&n.id);
        let label = node_label(n);
        match n.shape {
            NodeShape::Stadium => {
                out.push_str(&format!(
                    "export function {id}(): void {{\n    // {label}\n}}\n\n"
                ));
            }
            NodeShape::Cylinder => {
                out.push_str(&format!("export interface {id} {{}}\n\n"));
            }
            NodeShape::Diamond => {
                out.push_str(&format!("// decision: {id} ({label})\n"));
            }
            NodeShape::Circle => {
                out.push_str(&format!("// external: {id} ({label})\n"));
            }
            NodeShape::Hexagon | NodeShape::Rect => {
                out.push_str(&format!("export const {id}: string = {label:?};\n"));
            }
        }
    }

    fn emit_sequence(s: &SequenceDiagram, out: &mut String) {
        let mut methods: std::collections::HashMap<&str, Vec<String>> =
            std::collections::HashMap::new();
        for m in &s.messages {
            let method = format!("    {}(args?: unknown): void {{}};\n", ident(&m.text));
            methods.entry(m.to.as_str()).or_default().push(method);
        }
        for p in &s.participants {
            if p.id == START_END {
                continue;
            }
            let id = type_ident(&p.id);
            out.push_str(&format!("export interface {id} {{\n"));
            if let Some(ms) = methods.get(p.id.as_str()) {
                for m in ms {
                    out.push_str(m);
                }
            }
            out.push_str("}\n\n");
        }
        for n in &s.notes {
            out.push_str(&format!(
                "// note ({}): {}\n",
                note_placement(n.placement),
                n.text
            ));
        }
        if !s.notes.is_empty() {
            out.push('\n');
        }
    }

    fn emit_state(s: &StateDiagram, out: &mut String) {
        let variants: Vec<&str> = s
            .states
            .iter()
            .filter(|st| !matches!(st.kind, StateNodeKind::StartEnd))
            .map(|st| st.id.as_str())
            .collect();
        if variants.is_empty() {
            out.push_str("// state diagram has no states.\n");
            return;
        }
        out.push_str(&format!(
            "export type States = '{}';\n\n",
            variants.join("' | '")
        ));
        out.push_str("// transitions:\n");
        for t in &s.transitions {
            out.push_str(&format!(
                "//   '{}' -> '{}' : {}\n",
                t.from, t.to, t.label
            ));
        }
        out.push('\n');
    }

    fn emit_er(e: &ErDiagram, out: &mut String) {
        for ent in &e.entities {
            let id = type_ident(&ent.id);
            out.push_str(&format!("export interface {id} {{\n"));
            for a in &ent.attributes {
                let (_, marker) = er_attr_marker(a);
                out.push_str(&format!(
                    "    {marker} {}: {};\n",
                    ident(&a.name),
                    ts_type(&a.type_name)
                ));
            }
            out.push_str("}\n\n");
        }
        for r in &e.relationships {
            out.push_str(&format!(
                "// {} {}--{} {}\n",
                type_ident(&r.from),
                r.from_card.symbol(),
                r.to_card.symbol(),
                type_ident(&r.to),
            ));
        }
        if !e.relationships.is_empty() {
            out.push('\n');
        }
    }
}

