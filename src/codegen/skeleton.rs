/// Convert an arbitrary id into a valid Rust-style type / function identifier.
fn ident(id: &str) -> String {
    let mut out = String::with_capacity(id.len());
    for (i, c) in id.chars().enumerate() {
        let ok = c.is_ascii_alphanumeric() || c == '_';
        if ok && !(i == 0 && c.is_ascii_digit()) {
            out.push(c);
        } else if c == ' ' || c == '-' || c == '.' || c == '/' {
            out.push('_');
        }
    }
    if out.is_empty() {
        out.push('_');
    }
    out
}

/// Identifier for a type / module — starts with uppercase by convention.
fn type_ident(id: &str) -> String {
    let mut s = ident(id);
    if let Some(c) = s.chars().next()
        && c.is_ascii_lowercase()
    {
        s = c.to_ascii_uppercase().to_string() + &s[1..];
    }
    s
}

/// Identifier for a `mod` — mirrors `ident`.
fn mod_ident(id: &str) -> String {
    ident(id)
}

fn member_name(m: &ClassMember) -> String {
    let t = m.text.trim().trim_start_matches('+').trim();
    if let Some(idx) = t.find(['(', ':']) {
        t[..idx].trim().to_string()
    } else {
        t.to_string()
    }
}

/// Split `"Shape for Point"` → `Some(("Shape", "Point"))`.
/// Recognizes both `"X for Y"` and `"impl X"` shapes used by the Rust
/// extractor when no trait is present.
fn split_impl_id(id: &str) -> Option<(String, String)> {
    if let Some(rest) = id.strip_prefix("impl ") {
        return Some(("_".to_string(), rest.to_string()));
    }
    if let Some(idx) = id.find(" for ") {
        return Some((
            id[..idx].trim().to_string(),
            id[idx + 5..].trim().to_string(),
        ));
    }
    None
}

/// Parse `+name: Type` or `+name` → optional Rust field declaration body.
fn rust_field_decl(m: &ClassMember) -> Option<String> {
    let t = m.text.trim().trim_start_matches('+').trim();
    if t.contains('(') {
        return None;
    }
    if let Some(idx) = t.find(':') {
        let name = t[..idx].trim();
        let ty = t[idx + 1..].trim();
        Some(format!("{name}: {ty}"))
    } else if !t.is_empty() {
        Some(t.to_string())
    } else {
        None
    }
}

/// Parse `+name(args)` or `+name(args) Ret` → Rust method signature.
fn rust_method_sig(m: &ClassMember) -> Option<String> {
    let t = m.text.trim().trim_start_matches('+').trim();
    let open = t.find('(')?;
    let name = t[..open].trim();
    let close = t.rfind(')').unwrap_or(t.len());
    let args = t[open + 1..close].trim();
    let after = t[close + 1..].trim();
    let ret = if let Some(stripped) = after.strip_prefix("->") {
        stripped.trim()
    } else if let Some(stripped) = after.strip_prefix(':') {
        stripped.trim()
    } else {
        ""
    };
    Some(if ret.is_empty() {
        format!("fn {name}({args})")
    } else {
        format!("fn {name}({args}) -> {ret}")
    })
}

/// Parse a member into a TypeScript field declaration body (no semicolon).
fn ts_field_decl(m: &ClassMember) -> Option<String> {
    let t = m.text.trim().trim_start_matches('+').trim();
    if t.contains('(') {
        return None;
    }
    if let Some(idx) = t.find(':') {
        let name = t[..idx].trim();
        let ty = t[idx + 1..].trim().trim_start_matches(':').trim();
        Some(format!("{name}: {}", ts_type(ty)))
    } else if !t.is_empty() {
        Some(format!("{t}: unknown"))
    } else {
        None
    }
}

/// Parse a member into a TypeScript method signature.
/// `interface_mode` is accepted for symmetry with the Rust variant but
/// currently unused; both interface and class bodies use the same shape
/// (the body is omitted and the caller appends `;` or `{ … }`).
fn ts_method_sig(m: &ClassMember, _interface_mode: bool) -> Option<String> {
    let t = m.text.trim().trim_start_matches('+').trim();
    let open = t.find('(')?;
    let name = t[..open].trim();
    let close = t.rfind(')').unwrap_or(t.len());
    let args = t[open + 1..close].trim();
    let after = t[close + 1..].trim();
    let ret = if let Some(stripped) = after.strip_prefix(':') {
        stripped.trim()
    } else {
        ""
    };
    let ret_ts = if ret.is_empty() {
        "void".to_string()
    } else {
        ts_type(ret)
    };
    Some(format!("{name}({args}): {ret_ts}"))
}

fn ts_type(t: &str) -> String {
    let t = t.trim();
    if t.is_empty() {
        return "unknown".into();
    }
    match t {
        "i32" | "i64" | "u32" | "u64" | "usize" | "isize" | "f32" | "f64" => "number".into(),
        "bool" => "boolean".into(),
        "String" | "str" | "&str" => "string".into(),
        _ => t.to_string(),
    }
}

fn er_attr_marker(a: &Attribute) -> (String, &'static str) {
    let ty = ts_type(&a.type_name);
    let marker = if a.pk { "/// PK\n    " } else { "" };
    (ty, marker)
}

fn arrow_str(k: RelationKind) -> &'static str {
    k.mermaid_str()
}

fn cardinality(r: &Relation) -> String {
    match (&r.from_card, &r.to_card) {
        (Some(f), Some(t)) => format!("{f}..{t}"),
        (Some(f), None) => f.clone(),
        (None, Some(t)) => t.clone(),
        (None, None) => String::new(),
    }
}

fn field_for_relation(r: &Relation) -> String {
    format!("{}: {}", ident(&r.to), ident(&r.to))
}

fn style_arrow(s: &crate::diagram::EdgeStyle) -> &str {
    s.arrow_str()
}

fn note_placement(p: crate::sequence::NotePlacement) -> &'static str {
    match p {
        crate::sequence::NotePlacement::LeftOf => "left of",
        crate::sequence::NotePlacement::RightOf => "right of",
        crate::sequence::NotePlacement::Over => "over",
    }
}

fn node_label(n: &Node) -> String {
    if n.text.is_empty() {
        n.id.clone()
    } else {
        n.text.clone()
    }
}

#[allow(dead_code)]
fn cardinality_from(c: Cardinality) -> &'static str {
    c.symbol()
}

