mod rust {
    use super::*;

    pub fn emit(doc: &Document) -> String {
        let mut out = String::new();
        out.push_str("// Generated by `diagram generate-skeleton` (non-AI, deterministic).\n");
        out.push_str("// Edit freely; signatures come from the canonical IR.\n\n");
        for diag in &doc.diagrams {
            emit_diagram(diag, &mut out);
        }
        if out.ends_with("\n\n") {
            out.pop();
        }
        out
    }

    fn emit_diagram(diag: &Diagram, out: &mut String) {
        match diag {
            Diagram::Class(c) => emit_class(c, out),
            Diagram::Flowchart(f) => emit_flowchart(f, out),
            Diagram::Sequence(s) => emit_sequence(s, out),
            Diagram::State(s) => emit_state(s, out),
            Diagram::Er(e) => emit_er(e, out),
            Diagram::Gantt(_) => {
                out.push_str("// Gantt charts do not map to a skeleton; nothing to emit.\n\n");
            }
        }
    }

    fn emit_class(cd: &ClassDiagram, out: &mut String) {
        // 1. Type declarations.
        for c in &cd.classes {
            emit_class_decl(c, out);
        }
        // 2. Relation-based fields (composition / aggregation / association /
        //    link / dependency) attached to the `from` side. Inheritance /
        //    Realization become `impl` blocks.
        let mut rels_by_from: std::collections::HashMap<&str, Vec<&Relation>> =
            std::collections::HashMap::new();
        for r in &cd.relations {
            rels_by_from.entry(r.from.as_str()).or_default().push(r);
        }
        for c in &cd.classes {
            if let Some(rs) = rels_by_from.get(c.id.as_str()) {
                for r in rs {
                    match r.kind {
                        RelationKind::Inheritance | RelationKind::Realization => {
                            out.push_str(&format!(
                                "impl {} for {} {{}}\n\n",
                                type_ident(&r.to),
                                type_ident(&c.id)
                            ));
                        }
                        _ => {
                            out.push_str(&format!(
                                "    {} // {} {} ({})\n",
                                field_for_relation(r),
                                arrow_str(r.kind),
                                type_ident(&r.to),
                                cardinality(r)
                            ));
                        }
                    }
                }
            }
        }
        // 3. Notes as comments.
        for n in &cd.notes {
            out.push_str(&format!(
                "// note for {}: {}\n",
                type_ident(&n.target),
                n.text
            ));
        }
        if !cd.notes.is_empty() {
            out.push('\n');
        }
    }

    fn emit_class_decl(c: &Class, out: &mut String) {
        let stereo = c.stereotype.as_deref().unwrap_or("");
        let id = type_ident(&c.id);
        if stereo == "interface" {
            out.push_str(&format!("trait {id} {{\n"));
            for m in &c.members {
                if let Some(sig) = rust_method_sig(m) {
                    out.push_str(&format!("    {sig} {{ todo!() }}\n"));
                }
            }
            out.push_str("}\n\n");
            return;
        }
        if stereo == "enumeration" {
            out.push_str(&format!("enum {id} {{\n"));
            for m in &c.members {
                let variant = member_name(m);
                if !variant.is_empty() {
                    out.push_str(&format!("    {variant},\n"));
                }
            }
            out.push_str("}\n\n");
            return;
        }
        if stereo == "service" {
            // `service` is an `impl Trait for Type` block (Rust). Re-emit
            // it as a proper impl block so re-extraction sees the same
            // shape; members go inside the impl.
            if let Some((trait_name, type_name)) = split_impl_id(&c.id) {
                out.push_str(&format!("impl {trait_name} for {type_name} {{\n"));
                for m in &c.members {
                    if let Some(sig) = rust_method_sig(m) {
                        out.push_str(&format!("    {sig} {{ todo!() }}\n"));
                    }
                }
                out.push_str("}\n\n");
                return;
            }
            // Fall through: malformed id, emit as struct.
        }
        // Default: struct (with method signatures interleaved as `impl`).
        out.push_str(&format!("struct {id} {{\n"));
        for m in &c.members {
            if let Some(field) = rust_field_decl(m) {
                out.push_str(&format!("    pub {field},\n"));
            }
        }
        out.push_str("}\n\n");
        // Methods go in a separate impl block (or an inherent impl for
        // classes without an interface).
        let methods: Vec<_> = c.members.iter().filter_map(rust_method_sig).collect();
        if !methods.is_empty() {
            out.push_str(&format!("impl {id} {{\n"));
            for sig in methods {
                out.push_str(&format!("    {sig} {{ todo!() }}\n"));
            }
            out.push_str("}\n\n");
        }
    }

    fn emit_flowchart(fc: &FcDiagram, out: &mut String) {
        // Stable order: process subgraphs by appearance, then top-level nodes
        // not in any subgraph.
        let in_subgraph: std::collections::HashSet<&str> = fc
            .subgraphs
            .iter()
            .flat_map(|s| s.nodes.iter().map(|n| n.as_str()))
            .collect();
        for sg in &fc.subgraphs {
            emit_subgraph(sg, fc, out);
        }
        for n in &fc.nodes {
            if !in_subgraph.contains(n.id.as_str()) {
                emit_node_decl(n, out);
            }
        }
        for e in &fc.edges {
            out.push_str(&format!(
                "// {} {} {}{}\n",
                ident(&e.from),
                style_arrow(&e.style),
                ident(&e.to),
                if e.label.is_empty() {
                    String::new()
                } else {
                    format!(" // {}", e.label)
                }
            ));
        }
        if !fc.edges.is_empty() {
            out.push('\n');
        }
    }

    fn emit_subgraph(sg: &Subgraph, fc: &FcDiagram, out: &mut String) {
        let id = mod_ident(&sg.id);
        out.push_str(&format!("pub mod {id} {{\n"));
        for nid in &sg.nodes {
            if let Some(n) = fc.nodes.iter().find(|n| &n.id == nid) {
                emit_node_decl(n, out);
            }
        }
        out.push_str("}\n\n");
    }

    fn emit_node_decl(n: &Node, out: &mut String) {
        let id = ident(&n.id);
        let label = node_label(n);
        match n.shape {
            NodeShape::Stadium => {
                out.push_str(&format!("fn {id}() {{\n    // {label}\n    todo!()\n}}\n\n"));
            }
            NodeShape::Cylinder => {
                out.push_str(&format!("struct {id};\n"));
            }
            NodeShape::Diamond => {
                out.push_str(&format!("// decision: {id} ({label})\n"));
            }
            NodeShape::Circle => {
                out.push_str(&format!("// external: {id} ({label})\n"));
            }
            NodeShape::Hexagon | NodeShape::Rect => {
                out.push_str(&format!("const {id}_LABEL: &str = {label:?};\n"));
            }
        }
    }

    fn emit_sequence(s: &SequenceDiagram, out: &mut String) {
        // Each participant becomes a struct; each message becomes a method
        // signature on the receiver's struct.
        let mut methods: std::collections::HashMap<&str, Vec<String>> =
            std::collections::HashMap::new();
        for m in &s.messages {
            methods
                .entry(m.to.as_str())
                .or_default()
                .push(format!("    /// {} -> {}\n    fn {}(&self) {{}}\n", m.from, m.text, ident(&m.text)));
        }
        for p in &s.participants {
            if p.id == START_END {
                continue;
            }
            let id = type_ident(&p.id);
            out.push_str(&format!("struct {id} {{}}\n"));
            if let Some(ms) = methods.get(p.id.as_str()) {
                out.push_str(&format!("impl {id} {{\n"));
                for m in ms {
                    out.push_str(m);
                }
                out.push_str("}\n");
            }
            out.push('\n');
        }
        for n in &s.notes {
            out.push_str(&format!(
                "// note ({}): {}\n",
                note_placement(n.placement),
                n.text
            ));
        }
        if !s.notes.is_empty() {
            out.push('\n');
        }
    }

    fn emit_state(s: &StateDiagram, out: &mut String) {
        let mut variants: Vec<&str> = Vec::new();
        for st in &s.states {
            if matches!(st.kind, StateNodeKind::StartEnd) {
                continue;
            }
            variants.push(st.id.as_str());
        }
        if variants.is_empty() {
            out.push_str("// state diagram has no states.\n");
            return;
        }
        out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n");
        out.push_str("pub enum States {\n");
        for v in &variants {
            out.push_str(&format!("    {},\n", type_ident(v)));
        }
        out.push_str("}\n\n");
        out.push_str("// transitions:\n");
        for t in &s.transitions {
            out.push_str(&format!(
                "//   {} -> {} : {}\n",
                type_ident(&t.from),
                type_ident(&t.to),
                t.label
            ));
        }
        out.push('\n');
    }

    fn emit_er(e: &ErDiagram, out: &mut String) {
        for ent in &e.entities {
            let id = type_ident(&ent.id);
            out.push_str(&format!("struct {id} {{\n"));
            for a in &ent.attributes {
                let (ty, marker) = er_attr_marker(a);
                out.push_str(&format!("    {marker} {}: {ty},\n", ident(&a.name)));
            }
            out.push_str("}\n\n");
        }
        for r in &e.relationships {
            out.push_str(&format!(
                "// {} {}--{} {}\n",
                type_ident(&r.from),
                r.from_card.symbol(),
                r.to_card.symbol(),
                type_ident(&r.to),
            ));
        }
        if !e.relationships.is_empty() {
            out.push('\n');
        }
    }
}

