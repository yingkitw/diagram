//! IR → compilable source skeleton (deterministic, non-AI).
//!
//! Walks a [`Document`] and emits a stub in the chosen [`Language`]:
//! signatures are real, bodies are empty, notes/comments carry documentation.
//! This is the **UML → Code** half of the code ↔ UML story.

use super::Language;
use crate::class::{Class, ClassDiagram, ClassMember, Relation, RelationKind};
use crate::diagram::{Diagram as FcDiagram, Node, NodeShape, Subgraph};
use crate::er::{Attribute, Cardinality, ErDiagram};
use crate::ir::{Diagram, Document};
use crate::sequence::SequenceDiagram;
use crate::state::{StateDiagram, StateNodeKind, START_END};

/// Emit a source skeleton for `doc` in `lang`. The output is always
/// compilable when paired with the appropriate toolchain (cargo / tsc).
pub fn skeleton(doc: &Document, lang: Language) -> String {
    match lang {
        Language::Rust => rust::emit(doc),
        Language::TypeScript => typescript::emit(doc),
    }
}

